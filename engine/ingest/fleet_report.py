"""Generate docs/fleet.md (selection method, null-rate report, normalization coverage)
from the actual selection result, so the published numbers can never drift from the data."""

from __future__ import annotations

import os
from collections import Counter
from pathlib import Path

from contracts.contract import enum
from engine.graph.normalize import normalize_manufacturer, table, type_info
from engine.ingest.fleet_select import RULE_FIELD_SOURCE, SelectionResult

# rule_fields with no Aircraft field and no OpenSky column behind them.
STRUCTURAL_GAPS = {
    "category": "OpenSky has only `categoryDescription` (a weight class, e.g. 'Large'), which is not the certification category (transport/normal/...) an AD means; the contract's Aircraft node has no field for it.",
    "equipment": "No installed-equipment data in the source.",
    "modification": "No STC / service-bulletin / AD-compliance history in the source.",
    "part_number": "No installed-part data in the source.",
}


def null_rate(records: list[dict[str, object]], field_name: str) -> tuple[int, int]:
    """(non-null count, total) for one Aircraft field."""
    return sum(1 for r in records if r[field_name] is not None), len(records)


def _pct(num: int, den: int) -> str:
    return "n/a" if den == 0 else f"{100 * num / den:.1f}%"


def null_rate_table(result: SelectionResult) -> str:
    cols = [("Demo fleet", result.fleet), ("Eligible pool (before caps)", result.pool),
            ("All transport-type rows in source", result.population)]
    head = "| rule_field | Aircraft field | " + " | ".join(f"{n} usable / null" for n, _ in cols) + " |"
    lines = [head, "|---|---|" + "---|" * len(cols)]
    for rf in enum("rule_field"):
        src = RULE_FIELD_SOURCE.get(rf)
        if src is None:
            lines.append(f"| {rf} | (none) | " + " | ".join("0.0% / **100.0%**" for _ in cols) + " |")
            continue
        cells = []
        for _, recs in cols:
            ok, total = null_rate(recs, src)
            cells.append(f"{_pct(ok, total)} / {_pct(total - ok, total)}")
        lines.append(f"| {rf} | {src} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _coverage(records: list[dict[str, object]]) -> dict[str, int]:
    mfr = [r["manufacturer"] for r in records if r["manufacturer"] is not None]
    return {
        "total": len(records),
        "mfr_present": len(mfr),
        "mfr_mapped": sum(1 for m in mfr if normalize_manufacturer(str(m)) is not None),
        "type_mapped": sum(1 for r in records if type_info(str(r["typecode"])) is not None),
    }


def _unmapped_manufacturers(records: list[dict[str, object]], limit: int = 8) -> list[tuple[str, int]]:
    c = Counter(str(r["manufacturer"]) for r in records
                if r["manufacturer"] is not None and normalize_manufacturer(str(r["manufacturer"])) is None)
    return c.most_common(limit)


def operator_table(result: SelectionResult) -> str:
    lines = ["| Operator (verbatim from source) | Aircraft | Types |", "|---|---|---|"]
    for op, n in sorted(result.operators.items(), key=lambda kv: (-kv[1], kv[0])):
        mix = Counter(str(r["typecode"]) for r in result.fleet if r["operator"] == op)
        lines.append(f"| {op} | {n} | {', '.join(f'{t} x{c}' for t, c in sorted(mix.items()))} |")
    return "\n".join(lines)


def family_table(result: SelectionResult) -> str:
    fam = Counter((type_info(str(r["typecode"])) or {}).get("family", "?") for r in result.fleet)
    return ", ".join(f"{f}: {n}" for f, n in sorted(fam.items()))


def _dropped_pct(result: SelectionResult) -> int:
    us_rows = dict(result.funnel)["3 icao24 in US allocation block"]
    return round(100 * (1 - len(result.pool) / us_rows))


def _empty_types(result: SelectionResult) -> str:
    present = {str(r["typecode"]) for r in result.fleet}
    absent = sorted(set(table()["types"]) - present)
    return ", ".join(absent) or "none"


def render(result: SelectionResult) -> str:
    p = result.params
    cov, pool_cov = _coverage(result.fleet), _coverage(result.pool)
    pop_cov = _coverage(result.population)
    funnel = "\n".join(f"| {name} | {n:,} |" for name, n in result.funnel)
    gaps = "\n".join(f"- **{k}**: {v}" for k, v in STRUCTURAL_GAPS.items())
    fleet_unmapped = ", ".join(f"`{m}` ({n})" for m, n in _unmapped_manufacturers(result.fleet)) or "none"
    unmapped = ", ".join(f"`{m}` ({n})" for m, n in _unmapped_manufacturers(result.population)) or "none"
    return f"""# Fleet data layer (OpenSky)

Generated by `python3 -m engine.ingest.fleet --demo-fleet`; do not edit by hand.
Source: OpenSky aircraft database (`data/raw/fleet/aircraftDatabase.csv`), real registrations and serial numbers.
Nothing is invented: an empty source cell is `null`, and `null` is what makes the rules engine answer CANNOT_DETERMINE.

## Demo fleet

**{len(result.fleet)} aircraft, {len(result.operators)} operators** (families: {family_table(result)}).
Output: `data/build/nodes.aircraft.jsonl` (contract `Aircraft` nodes, `_type: "Aircraft"`), merged into
`data/build/nodes.jsonl` by `python3 -m engine.graph.aircraft_nodes --merge` (replaces only Aircraft lines; every other
line is preserved byte-for-byte; idempotent).

### How the fleet was selected (selection bias, stated)

A single deterministic pass over the CSV; every filter is a rule, none is a hand pick:

| Stage | Rows remaining |
|---|---|
{funnel}

1. A row needs a `registration` (it is the node key). Duplicate registrations keep the first row.
2. `typecode` must be in the normalization table (`data/reference/aircraft_normalization.json`): Boeing 737 (classic, NG, MAX), 757, 767, 777, 787; Airbus A319/A320/A321 (incl. neo), A330, A350; Embraer E170/E175/E190/E195; De Havilland/Bombardier Dash 8 (DHC-8-100..400); ATR 42/72. These are the transport types named in the brief; the NPRM corpus makes include Boeing, Airbus, Embraer and Bombardier.
3. `icao24` inside the US allocation block {p["US_ICAO24"]} (a structured field, not a guess from the tail number): FAA ADs apply to US-registered aircraft.
4. `serial_number` present (needed for serial-range rules).
5. `operator` present (needed to group rows in the BlastRadius grid).
6. If a manufacturer is present it must not contradict the typecode's manufacturer.
7. Operators with at least {p["MIN_PER_OPERATOR"]} eligible aircraft are ranked by eligible count (ties by name). Each contributes at most {p["MAX_PER_OPERATOR"]}, taken in ascending SHA-1 of the tail number (stable, unrelated to any attribute), until {p["MAX_FLEET"]} would be exceeded.

Table types with no aircraft in this fleet (no US-block row met every filter): {_empty_types(result)}.

**Caveats to state on stage.** The fleet over-represents the large US carriers and cargo operators; it is not a random sample of the world fleet. Requiring serial and operator drops {_dropped_pct(result)}% of US-block transport rows (operator is blank in most OpenSky rows), so in this fleet **serial_number and operator are 0% null by construction**, and typecode too (it defines the type filter). Manufacturer and model are also 0% null here, but only because the rows that carry an operator are the better-populated ones. These are selection artifacts, not a property of the data. The right-hand columns show the unfiltered base rates. Operator strings are verbatim, so `Alaska Airlines` and `Alaska Airlines, Inc.` are separate rows; no operator merging was done.

## Null-rate report

Share of aircraft with a usable (non-null) value / share that are null, per contract `rule_field`.

{null_rate_table(result)}

### Structurally unavailable rule_fields

These four contract `rule_field`s have no source column, so they are 100% null in every fleet built from OpenSky. **Every AD rule conditioned on them resolves to CANNOT_DETERMINE** for every aircraft:

{gaps}

Also dropped by design: OpenSky `status`, `registered`, `reguntil`, `firstflightdate`, `seatconfiguration`, `categoryDescription`, etc. (not in the contract `Aircraft` node). `built_year` is the year of OpenSky's `built` date; the source's `0001-01-01` placeholder is treated as unknown (null).

## Normalization (manufacturer / model join with AD text)

`data/reference/aircraft_normalization.json` is an explicit table: OpenSky manufacturer aliases and AD `make` forms per canonical manufacturer, and ICAO typecode -> family and AD series names (`B738` -> `737-800`). Matching is casefold + whitespace collapse only; there is no fuzzy matching. API: `engine/graph/normalize.py`.

| Population | Rows | typecode mapped | manufacturer present | manufacturer present and mapped |
|---|---|---|---|---|
| Demo fleet | {cov["total"]} | {_pct(cov["type_mapped"], cov["total"])} (by selection) | {_pct(cov["mfr_present"], cov["total"])} | {_pct(cov["mfr_mapped"], cov["mfr_present"])} |
| Eligible pool | {pool_cov["total"]} | {_pct(pool_cov["type_mapped"], pool_cov["total"])} (by selection) | {_pct(pool_cov["mfr_present"], pool_cov["total"])} | {_pct(pool_cov["mfr_mapped"], pool_cov["mfr_present"])} |
| All transport-type rows | {pop_cov["total"]} | {_pct(pop_cov["type_mapped"], pop_cov["total"])} (by selection) | {_pct(pop_cov["mfr_present"], pop_cov["total"])} | {_pct(pop_cov["mfr_mapped"], pop_cov["mfr_present"])} |

Most frequent unmapped manufacturer strings among all transport-type rows (data-entry noise; left unmapped, never guessed): {unmapped}.
Unmapped manufacturer strings inside the demo fleet itself: {fleet_unmapped}. (Left unmapped because the alias could not be verified from the data alone; adding it is a one-line table edit once confirmed.)
Model strings are kept verbatim in `Aircraft.model` (e.g. `737-823`, `ERJ 170-200 LR`); the table joins at type/series level (`ad_models`), and variant-level matching is the rules engine's `model_matches` job on the raw string. A null manufacturer is **not** back-filled from the typecode: that would be a derived value, not source data.
"""


def write_fleet_doc(result: SelectionResult, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(render(result), encoding="utf-8")
    os.replace(tmp, path)
